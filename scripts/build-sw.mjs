import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const outputUrl = new URL('public/sw.js', root);
const inputs = ['src/lib/swRouting.ts', 'src/service-worker.ts'];

/** A small local bundle: erase TS/module syntax, retaining readable source. */
export async function generateServiceWorker() {
  const sources = await Promise.all(inputs.map((name) => readFile(new URL(name, root), 'utf8')));
  const parts = sources.map((source, index) => {
    const result = ts.transpileModule(source, {
      fileName: inputs[index],
      compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false },
      transformers: { before: [(context) => (file) => ts.visitNode(file, function visit(node) {
        if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) return undefined;
        if (ts.canHaveModifiers(node)) {
          const modifiers = ts.getModifiers(node);
          if (modifiers?.some((item) => item.kind === ts.SyntaxKind.ExportKeyword)) {
            node = context.factory.replaceModifiers(node, modifiers.filter((item) => item.kind !== ts.SyntaxKind.ExportKeyword));
          }
        }
        return ts.visitEachChild(node, visit, context);
      })] },
    });
    // TypeScript emits an empty export for a source originally marked as a
    // module, even after its local imports/exports were stripped above.
    return `// Source: ${inputs[index]}\n${result.outputText.replace(/^export \{\};\r?$/gm, '').trimEnd()}`;
  });
  return `// Generated by scripts/build-sw.mjs. Do not edit; run npm run prebuild.\n(() => {\n'use strict';\n${parts.join('\n\n')}\n})();\n`;
}

export function assertServiceWorkerCurrent(committed, generated) {
  if (committed !== generated) throw new Error('public/sw.js is stale. Run npm run prebuild and commit the result.');
}

export async function buildServiceWorker({ check = false } = {}) {
  const generated = await generateServiceWorker();
  if (check) {
    assertServiceWorkerCurrent(await readFile(outputUrl, 'utf8'), generated);
    console.log('Service worker is current.');
  } else {
    await writeFile(outputUrl, generated);
    console.log('Generated public/sw.js from shared routing and cache policy.');
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) await buildServiceWorker({ check: process.argv.includes('--check') });
